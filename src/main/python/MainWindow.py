    def on_topic_update(self, topic, message, sender):
        if topic == "show_error_message":
            message = f"Error: {message}"
            QtWidgets.QMessageBox.critical(self, "Error", message)
        elif topic == "show_info_message":
            message = f"{message}"
            QtWidgets.QMessageBox.information(self, "Info", message)
        elif topic == "minimize":
            self.showMinimized()
        elif topic == "maximize":
            self.showNormal()

    def closeEvent(self, event):
        """Handle application closing - ensure proper memory cleanup."""
        try:
            # Close any open apps first
            if hasattr(self._managers, 'app_manager'):
                self._managers.app_manager.close_app()

            # Close any open tools
            if hasattr(self._managers, 'tool_manager'):
                self._managers.tool_manager.unload_content()

            # Close any open processes
            if hasattr(self._managers, 'process_manager'):
                self._managers.process_manager.close_process()
                
            # Perform comprehensive memory cleanup
            if hasattr(self._managers, 'package_manager'):
                self._managers.package_manager.cleanup_for_shutdown()
                
        except Exception as e:
            # Don't let cleanup errors prevent app closure
            print(f"Warning: Error during cleanup: {e}")
        
        # Accept the close event
        event.accept()

    # Private functions
    def _init_themes(self):
        """ Init the themes """
        QtWidgets.QApplication.setStyle(SnoozStyle())

        # The colors of the light theme are defined once in its tokens.json,
        # shared by the Qt palette below and the style sheet.
        light_tokens = load_tokens(":/themes/light/tokens.json")
        QtWidgets.QApplication.setPalette(self._create_qt_palette(light_tokens))

        light_style_name = "Light"
        light_palette = Palette()
        light_palette.grid_background = QtGui.QColor(247, 250, 251)
        light_palette.grid_line = QtGui.QColor(181,196,201)
        light_palette.node_selection = QtGui.QColor(light_tokens["primary"])
        light_palette.node_background_activated = QtGui.QColor(195, 211, 217)
        light_palette.node_background_deactivated = QtGui.QColor(102,102,102)
        light_palette.node_background_bypass = QtGui.QColor(247,250,251)
        light_palette.node_border = QtGui.QColor(102, 102, 102)
        light_palette.node_text = QtGui.QColor(31,31,31)
        light_palette.node_socket_border = QtGui.QColor(102, 102, 102)
        light_palette.node_socket_background = QtGui.QColor(206, 208, 209)

        light_style = Style(light_style_name, light_palette, ":/themes/light/stylesheet.qss",
            ":/themes/light/tokens.json")
        self._managers.style_manager.register_style(light_style)
        self._managers.style_manager.set_default_style(light_style_name)
        self._managers.style_manager.load_user_style()
        self._init_window_chrome(light_tokens)

    def _init_window_chrome(self, tokens):
        """ Round menus, navigation icons and title bar color. """
        for menu in self.menuBar.findChildren(QtWidgets.QMenu):
            round_menu_corners(menu)

        # The checked navigation button is the current page (see NavigationManager).
        for button, glyph in ((self.home_pushButton, "home"), (self.tool_pushButton, "tool"),
                              (self.process_pushButton, "process"), (self.app_pushButton, "app")):
            button.setCheckable(True)
            button.setIcon(nav_icon(glyph, tokens))

        # Applied when the window is shown, see showEvent.
        self._title_bar_colors = (tokens["chrome"], tokens["chrome_text"])

    def showEvent(self, event):
        super().showEvent(event)
        # Title bar in the color of the menu bar (Windows 11)
        set_title_bar_color(self, *self._title_bar_colors)

    @staticmethod
    def _create_qt_palette(tokens):
        """ Create the Qt palette (used by the Fusion style) from the color tokens of a theme. """
        def color(name):
            return QtGui.QColor(tokens[name])

        palette = QtGui.QPalette()
        palette.setColor(QtGui.QPalette.Window, color("surface"))
        palette.setColor(QtGui.QPalette.WindowText, color("text"))
        palette.setColor(QtGui.QPalette.Base, color("surface"))
        palette.setColor(QtGui.QPalette.AlternateBase, color("surface_alt"))
        palette.setColor(QtGui.QPalette.ToolTipBase, color("surface"))
        palette.setColor(QtGui.QPalette.ToolTipText, color("text"))
        palette.setColor(QtGui.QPalette.PlaceholderText, color("placeholder"))
        palette.setColor(QtGui.QPalette.Text, color("text"))
        palette.setColor(QtGui.QPalette.Button, color("surface_alt"))
        palette.setColor(QtGui.QPalette.ButtonText, color("text"))
        palette.setColor(QtGui.QPalette.BrightText, QtCore.Qt.red)
        palette.setColor(QtGui.QPalette.Highlight, color("selection"))
        palette.setColor(QtGui.QPalette.HighlightedText, color("on_selection"))
        palette.setColor(QtGui.QPalette.Link, color("link"))
        palette.setColor(QtGui.QPalette.LinkVisited, color("link"))

        disabled = QtGui.QPalette.Disabled
        for role in (QtGui.QPalette.WindowText, QtGui.QPalette.Text, QtGui.QPalette.ButtonText):
            palette.setColor(disabled, role, color("text_disabled"))
        palette.setColor(disabled, QtGui.QPalette.PlaceholderText, color("placeholder_disabled"))
        palette.setColor(disabled, QtGui.QPalette.Base, color("disabled_bg"))
        palette.setColor(disabled, QtGui.QPalette.Button, color("disabled_bg"))
        return palette

    def _init_homepage(self):
        """ Init the homepage """
        # The home page replaces the panes of the Qt Designer form.
        self.left_pane.setVisible(False)
        self.right_pane_layout.addWidget(HomeWidget(self._managers, self))

    def _init_fonts(self):
        fonts = [
            "fonts/Roboto/Roboto-Regular.ttf"
        ]
        # Load fonts
        for font_path in fonts:
            release_notes_path = config.app_context.get_resource(font_path)
            fontId = QtGui.QFontDatabase.addApplicationFont(release_notes_path)
            if fontId < 0:
                print('font not loaded')
        
        families = QtGui.QFontDatabase.applicationFontFamilies(0)
        font = QtGui.QFont(families[0])
        font.setPointSize(config.font_size)
        QtWidgets.QApplication.setFont(font)
        return font
    

    def _display_disclaimer(self):
        """ Display the beta version disclaimer """
        skip = self._managers.settings_manager.get_setting(config.settings.skip_beta_disclaimer, None)
        if skip is None:
            disclaimer_dialog = DisclaimerDialog(self._managers.settings_manager)
            disclaimer_dialog.exec_()


